/** The locale a page of the site is in, from its own tag (`zh-Hans`, `es`, `en`), English when it names none. */
export function localeOf(tag) {
    const lower = String(tag ?? '').toLowerCase();
    if (lower.startsWith('zh')) return 'zh-Hans';
    if (lower.startsWith('es')) return 'es';
    return 'en';
}

/** One string, its {placeholders} filled. A locale that lacks one falls back to English (the build's TRANSLATING gate). */
export function t(locale, key, values = {}) {
    const table = STRINGS[locale] ?? STRINGS.en;
    const text = table[key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
